// Build-time glob of companion pictures.
//
// The images live in public/companions/<id>/ (served from the site root) — they
// are static assets, not part of the module graph, so nothing imports them and
// there's no runtime way to list a public folder in a client bundle. This script
// globs each companion's folder and writes the list into a generated TS module
// the config imports, so `companion.pictures` is a plain, synchronous array of
// { src, description }. A picture's description comes from an optional sidecar
// text file beside it — <basename>.txt — so descriptions live next to the images
// and out of source. It runs automatically before `dev` and `build`
// (predev/prebuild in package.json); run it by hand with `npm run gen:pictures`
// after adding images while a dev server is already up.

import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname, basename, extname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const companionsDir = join(root, "public", "companions");
const outFile = join(
  root,
  "src",
  "lib",
  "companions",
  "companion-pictures.generated.ts",
);

const IMAGE_RE = /\.(jpe?g|png|webp|gif|avif)$/i;

// The description beside an image: <basename>.txt, trimmed; "" when absent.
function descriptionFor(dir, file) {
  const txt = join(dir, `${basename(file, extname(file))}.txt`);
  if (!existsSync(txt)) return "";
  return readFileSync(txt, "utf8").trim();
}

// One entry per public/companions/<id>/ folder → sorted list of { src,
// description }. Sorted by filename so the output is stable between runs.
const byCompanion = {};
if (existsSync(companionsDir)) {
  for (const id of readdirSync(companionsDir, { withFileTypes: true })) {
    if (!id.isDirectory()) continue;
    const dir = join(companionsDir, id.name);
    const files = readdirSync(dir)
      .filter((f) => IMAGE_RE.test(f))
      .sort();
    // Only pictures with a (non-empty) sidecar description are included — an
    // image with no <basename>.txt is skipped, so she never sends one she can't
    // describe. Drop an image by deleting its .txt.
    byCompanion[id.name] = files
      .map((f) => ({
        src: `/companions/${id.name}/${f}`,
        description: descriptionFor(dir, f),
      }))
      .filter((p) => p.description !== "");
  }
}

// Emit in Prettier's default style so `npm run format` never rewrites the
// generated file (which would churn against the next regeneration): object keys
// unquoted when they're valid identifiers, double-quoted strings, one field per
// line, trailing commas.
const identKey = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));

// A `key: "value",` object field at 6-space indent, matching Prettier: kept on
// one line when it fits Prettier's 80-column width, else broken with the value
// on the next line (indented 8). Keeps the generated file format-stable so a
// build's regeneration never leaves it needing `npm run format`.
const field = (key, value) => {
  const inline = `      ${key}: ${JSON.stringify(value)},`;
  if (inline.length <= 80) return inline;
  return `      ${key}:\n        ${JSON.stringify(value)},`;
};

const body = Object.entries(byCompanion)
  .map(([id, pics]) => {
    const lines = pics
      .map(
        (p) =>
          `    {\n${field("src", p.src)}\n${field(
            "description",
            p.description,
          )}\n    },`,
      )
      .join("\n");
    return `  ${identKey(id)}: [\n${lines}\n  ],`;
  })
  .join("\n");

// Empty → Prettier collapses `{\n\n}` to `{}`, so emit the collapsed form
// directly to stay format-stable when no companion has any pictures.
const record = body === "" ? "{}" : `{\n${body}\n}`;

const out = `// AUTO-GENERATED by scripts/generate-companion-pictures.mjs — do not edit.
// Regenerated before every dev/build; run \`npm run gen:pictures\` to refresh.
// Keyed by companion id; each value is that companion's pictures, globbed from
// public/companions/<id>/, with descriptions from sidecar <basename>.txt files.
export type GeneratedPicture = { src: string; description: string };
export const COMPANION_PICTURES: Record<string, GeneratedPicture[]> = ${record};
`;

writeFileSync(outFile, out);
console.log(
  `generate-companion-pictures: wrote ${Object.values(byCompanion).reduce(
    (n, s) => n + s.length,
    0,
  )} picture(s) across ${Object.keys(byCompanion).length} companion(s)`,
);
